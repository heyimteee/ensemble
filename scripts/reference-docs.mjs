/** Top-level field names from a flat exported object type. */
export function typeFieldNames(relative, typeName) {
  const source = readSource(relative)
  const block = new RegExp(`export type ${typeName} = \\{([\\s\\S]*?)\\n\\}`).exec(source)
  if (!block) throw new Error(`could not find export type ${typeName} in ${relative}`)
  const body = block[1]
  const fields = []
  for (const line of body.split(/\r?\n/)) {
    const match = /^ {2}([A-Za-z][A-Za-z0-9]*)\??:/.exec(line)
    if (match) fields.push(match[1])
  }
  if (fields.length === 0) throw new Error(`no fields parsed from ${typeName} in ${relative}`)
  return fields
}

