function keyboardEntriesForSection(section) {
  // Key ids are stable inside one context, not across the whole catalog: the
  // same `escape` id exists for roster, chat, and work. Key the lookup by the
  // help source's context as well as the id.
  const byContextID = new Map()
  for (const entry of KEYMAP_CATALOG) {
    if (entry.scope === "leader") {
      byContextID.set(`leader:${entry.id}`, entry)
      continue
    }
    for (const context of entry.contexts) byContextID.set(`${context}:${entry.id}`, entry)
  }
  return section.entries
    .filter((entry) => entry.source.kind === "keymap")
    .map((entry) => {
      const catalog = byContextID.get(`${entry.source.context}:${entry.source.id}`)
      if (!catalog) {
        throw new Error(`help entry ${entry.id} names an unknown keymap id ${entry.source.id} in ${entry.source.context}`)
      }
      return { ...catalog, helpKeys: entry.keys, helpContext: entry.source.context }
    })
}

function keyDisplay(entry) {
  const chord = keyChordLabel(entry.keys)
  return entry.scope === "leader" ? `Space ${chord}` : chord
}

function keyNote(entry) {
  const notes = []
  if (entry.requires === "work") notes.push("Only while the Work pane has rows.")
  if (entry.requires === "multi") notes.push("Only with multiple candidates.")
  if (entry.requires === "memory") notes.push("Only in a memory field.")
  if (entry.availability === "no-transcript-search") notes.push("Unavailable while transcript search is open.")
  if (entry.listed === false) notes.push("Hidden from which-key hints; help still lists it.")
  return notes.join(" ") || "—"
}

