function sourceFiles(relative) {
  const out = []
  for (const entry of readdirSync(join(REPO_ROOT, relative), { withFileTypes: true })) {
    if (entry.isDirectory()) {
      out.push(...sourceFiles(join(relative, entry.name)))
      continue
    }
    if (!/\.tsx?$/.test(entry.name) || entry.name.endsWith(".test.ts") || entry.name.endsWith(".test.tsx")) continue
    out.push(join(relative, entry.name))
  }
  return out
}

/**
 * Non-test product environment reads. The one indirect read is declared next
 * to its source constant because the key is a variable, not a literal.
 */
export function sourceEnvironmentNames() {
  const names = new Set()
  for (const file of sourceFiles("src")) {
    const text = readSource(file)
    for (const match of text.matchAll(/\benv\.([A-Z][A-Z0-9_]+)/g)) names.add(match[1])
    for (const match of text.matchAll(/process\.env\.([A-Z][A-Z0-9_]+)/g)) names.add(match[1])
    for (const match of text.matchAll(/process\.env\[["']([A-Z][A-Z0-9_]+)["']\]/g)) names.add(match[1])
  }
  // `src/v2/store.ts` reads this through CLONE_DEBUG_ENV.
  if (readSource("src/v2/store.ts").includes('CLONE_DEBUG_ENV = "ENSEMBLE_DEBUG_CLONES"')) {
    names.add("ENSEMBLE_DEBUG_CLONES")
  }
  names.delete("NODE_TEST_CONTEXT")
  return [...names].sort()
}

