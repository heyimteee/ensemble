function schemaRows(schema, required = schema.required ?? []) {
  const properties = schema.properties ?? {}
  const rows = Object.entries(properties).map(([name, spec]) => {
    const bits = []
    if (spec.type) bits.push(code(spec.type))
    if (spec.enum) bits.push(spec.enum.map((value) => code(value)).join(", "))
    if (spec.minimum !== undefined) bits.push(`minimum ${spec.minimum}`)
    const notes = []
    if (required.includes(name)) notes.push("required")
    if (spec.description) notes.push(escapeCell(spec.description))
    return [code(name), bits.join(" "), notes.join("; ") || "—"]
  })
  return table(["Field", "Type", "Notes"], rows)
}

function toolInputDetails(tool) {
  const input = tool.input
  if (!input.properties || Object.keys(input.properties).length === 0) return "This tool takes no inputs."
  const sections = [schemaRows(input)]
  const decisions = input.properties?.decisions?.items
  if (decisions) {
    sections.push("**`decisions[]` item**\n\n" + schemaRows(decisions))
  }
  const assignments = input.properties?.assignments?.items
  if (assignments) {
    sections.push("**`assignments[]` item**\n\n" + schemaRows(assignments))
  }
  return sections.join("\n\n")
}

function assertToolDocumentation() {
  const native = NATIVE_TOOLS.map((tool) => tool.base)
  for (const base of native) {
    if (!(base in NATIVE_TOOL_DOCS)) throw new Error(`missing documentation for native tool ensemble_${base}`)
  }
  for (const base of Object.keys(NATIVE_TOOL_DOCS)) {
    if (!native.includes(base)) throw new Error(`stale documentation for native tool ensemble_${base}`)
  }
  const legacyOnly = LEGACY_TOOLS.filter((tool) => !TOOL_SURFACE_TOOL_NAMES.native.includes(tool.base)).map(
    (tool) => tool.base,
  )
  for (const base of legacyOnly) {
    if (!(base in LEGACY_TOOL_DOCS)) throw new Error(`missing documentation for legacy tool ensemble_${base}`)
  }
  for (const base of Object.keys(LEGACY_TOOL_DOCS)) {
    if (!legacyOnly.includes(base)) throw new Error(`stale documentation for legacy tool ensemble_${base}`)
  }
}

