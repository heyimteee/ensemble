/** Drive the real registrar with a fake editor and capture what it registers. */
export function registeredTools(surface) {
  const tools = []
  let namespace = "ensemble"
  registerEnsembleTools(
    {
      namespace(definition) {
        namespace = definition.name
      },
      add(tool) {
        tools.push({
          base: tool.name,
          name: `${namespace}_${tool.name}`,
          description: tool.description,
          input: tool.input,
          options: tool.options,
        })
      },
    },
    STUB_HANDLERS,
    surface,
  )
  return tools
}

function assertSurfaceNames(surface) {
  const registered = registeredTools(surface).map((tool) => tool.base)
  const expected = TOOL_SURFACE_TOOL_NAMES[surface]
  if (registered.join(",") !== expected.join(",")) {
    throw new Error(
      `tool surface ${surface} registration drifted: registrar ${registered.join(",")}; catalog ${expected.join(",")}`,
    )
  }
}

